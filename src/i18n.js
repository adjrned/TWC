const STORAGE_KEY = 'twrpg_locale';
let currentLocale = localStorage.getItem(STORAGE_KEY) || 'en';

export function getLocale() {
  return currentLocale;
}

export function setLocale(locale) {
  if (!STRINGS[locale]) return;
  currentLocale = locale;
  localStorage.setItem(STORAGE_KEY, locale);
  document.documentElement.lang = locale;
  window.dispatchEvent(new CustomEvent('locale-change', { detail: { locale } }));
}

export function t(key, replacements) {
  let str = STRINGS[currentLocale]?.[key] || STRINGS.en[key] || key;
  if (replacements) {
    for (const [k, v] of Object.entries(replacements)) {
      str = str.replace(`{${k}}`, v);
    }
  }
  return str;
}

// Like t(), but returns `fallback` when the key has no translation in any locale.
export function tf(key, fallback) {
  const v = t(key);
  return v === key ? fallback : v;
}

